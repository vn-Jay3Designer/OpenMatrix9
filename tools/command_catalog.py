"""Write docs/matrix9-commands.md: every command of the OM9 menus (MainMenu.ini) with its
menu position, icon, feature name and who provides it (core, an add-on in addons/, or
planned). Inputs are repository files only; run it after adding add-on commands.

    python3 tools/command_catalog.py          # rewrite the catalog
    python3 tools/command_catalog.py --check  # fail if the catalog is out of date
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MENUS = ["Curve", "Surface", "Solid", "Transform", "Clayoo", "Builder", "Tools", "Gems",
         "Settings", "Cutters"]
GROUP = {"Clayoo": "SubD (Clayoo)"}
CORE = {"OM9-CURVE-002": "core Line", "OM9-CURVE-034": "core Point"}


def ini_sections(text):
    sections, current = {}, None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("[") and line.endswith("]"):
            current = sections.setdefault(line[1:-1], {})
        elif "=" in line and current is not None:
            k, v = line.split("=", 1)
            current[k.strip()] = v.strip()
    return sections


def icons():
    src = (ROOT / "crates/om9-app/src/icons.rs").read_text(encoding="utf-8")
    out = {}
    for name, key, feature, svg in re.findall(
            r'icon!\(\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)"\s*\)', src):
        out.setdefault(key, (name, feature, svg))
    return out


def addon_commands():
    out = {}
    for manifest in sorted(ROOT.glob("addons/*/addon/om9_addon.toml")) + sorted(
            ROOT.glob("addons/*/om9_addon.toml")):
        text = manifest.read_text(encoding="utf-8")
        addon = re.search(r'(?m)^id\s*=\s*"([^"]+)"', text).group(1)
        for block in text.split("[[commands]]")[1:]:
            m = re.search(r'(?m)^id\s*=\s*"([^"]+)"', block)
            if not m:
                continue
            kinds = [k for k in ("interactive", "builder")
                     if re.search(rf'(?m)^{k}\s*=\s*true', block)]
            aliases = re.search(r'(?m)^aliases\s*=\s*\[([^\]]*)\]', block)
            alias = ", ".join(a.strip().strip('"') for a in aliases.group(1).split(",")
                              if a.strip()) if aliases else ""
            out[m.group(1)] = (addon, "+".join(kinds) or "run", alias)
    return out


def render():
    sections = ini_sections((ROOT / "Resources/menu/MainMenu.ini").read_text(encoding="utf-8"))
    features = {f["id"]: f for f in json.loads(
        (ROOT / "crates/om9-app/assets/features.json").read_text(encoding="utf-8"))}
    palette, addons = icons(), addon_commands()
    menus = {s["Name"]: s for k, s in sections.items() if k.startswith("Menu") and "Name" in s}
    lines = ["# Matrix-style command catalog",
             "",
             "Generated by `tools/command_catalog.py` from `Resources/menu/MainMenu.ini`,",
             "`crates/om9-app/src/icons.rs`, `crates/om9-app/assets/features.json` and the",
             "add-on manifests. Do not edit by hand.",
             "",
             "- **Position**: the slot in the menu palette, counted left to right and top to bottom.",
             "- **Icon**: the authored SVG under `Resources/icons/`.",
             "- **Provided by**:",
             "  - `core`: built into OM9;",
             "  - an add-on id, with its interaction type and command-line aliases;",
             "  - `planned`: not available yet.",
             ""]
    totals = []
    for menu in ["Top11"] + MENUS:
        if menu == "Top11":
            sec, title, colour = sections["Top11"], "Top 11 buttons", "-"
            count = len([k for k in sec if k.startswith("Icon")])
        else:
            sec = menus[menu]
            title, colour = GROUP.get(menu, menu), sec.get("Color", "")
            count = int(sec.get("IconCount", 0))
        done = 0
        rows = []
        for i in range(1, count + 1):
            code = sec.get(f"Icon{i}", "")
            name, feature, svg = palette.get(code, ("", "", ""))
            fname = features.get(feature, {}).get("name", "") if feature else ""
            if code in addons:
                addon, kind, alias = addons[code]
                status = f"`{addon}` ({kind})" + (f" — `{alias}`" if alias else "")
                done += 1
            elif feature in CORE and palette.get(code, ("", "", ""))[0] in ("Line", "Point"):
                status = "core"
                done += 1
            else:
                status = "planned"
            rows.append(f"| {i} | `{code}` | {fname or name or '—'} | "
                        f"{('`' + svg + '`') if svg else '—'} | {status} |")
        totals.append((title, done, count))
        lines += [f"## {title}", "", f"Menu colour: {colour}. Available: {done}/{count}.", "",
                  "| Position | Code | Name | Icon | Provided by |",
                  "|---|---|---|---|---|", *rows, ""]
    summary = ["## Summary", "", "| Group | Available | Commands |", "|---|---|---|"]
    summary += [f"| {t} | {d} | {c} |" for t, d, c in totals]
    summary += [f"| **All** | **{sum(d for _, d, _ in totals)}** | "
                f"**{sum(c for _, _, c in totals)}** |", ""]
    return "\n".join(lines[:13] + summary + lines[13:])


def main():
    out = ROOT / "docs/matrix9-commands.md"
    text = render()
    if "--check" in sys.argv:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            sys.exit("docs/matrix9-commands.md is out of date: run tools/command_catalog.py")
        return
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
